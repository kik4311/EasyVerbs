function getSystemLang() {
    return navigator.language && navigator.language.startsWith('en') ? 'en' : 'ru';
}

function __(key) {
    const lang = settings.lang || getSystemLang();
    return (translations[lang] && translations[lang][key] !== undefined) ? translations[lang][key] : (translations['ru'][key] || key);
}

function applyLanguage() {
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
        const key = el.getAttribute('data-i18n');
        if (el.tagName === 'INPUT' && el.type === 'text') {
            el.placeholder = __(key);
        } else if (el.tagName === 'INPUT' && el.type !== 'text') {
        } else {
            el.textContent = __(key);
        }
    });
    document.querySelectorAll('[data-i18n-title]').forEach(function(el) {
        el.setAttribute('title', __(el.getAttribute('data-i18n-title')));
    });
    const langSelect = document.getElementById('setting-lang');
    if (langSelect) langSelect.value = settings.lang || getSystemLang();
}
